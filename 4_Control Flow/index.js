
/* 
    # Control Flow
      > Control flow refers to the order in which the code is executed in a program. It allows developers to make decisions, repeat actions, and control the flow of execution based on certain conditions.

        1. Conditional Statements
          > Conditional statements allow you to execute different blocks of code based on certain conditions. The main types of conditional statements in JavaScript are:

            - if statement
            - if...else statement
            - if...else if...else statement
            - switch statement

        2. Loops
          > Loops allow you to execute a block of code repeatedly as long as a specified condition is true. The main types of loops in JavaScript are:

            - for loop
            - while loop
            - do...while loop
            - for...in loop
            - for...of loop

        3. Break and Continue
          > The break statement is used to exit a loop or switch statement prematurely, while the continue statement is used to skip the current iteration of a loop and move on to the next one.

            - break statement
            - continue statement

        4. Ternary Operator
            > The ternary operator is a shorthand way of writing an if...else statement. It takes three operands: a condition, an expression to execute if the condition is true, and an expression to execute if the condition is false.
            
            - condition ? expressionIfTrue : expressionIfFalse


*/